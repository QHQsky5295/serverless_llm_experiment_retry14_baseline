"""Prepare the single same-spec 3B profile collection (D701).

D700 proved the missing class keys but deliberately used a six-identity gap
spec.  The frozen collector cannot merge that spec with D645's 24-identity
specification.  D701 therefore creates one new, append-only source
specification: it preserves every D645 wave and representative, changes only
the pre-registered output-bin boundaries, and appends the 30 already-prepared
gap waves.  No request, adapter, trace, or weight is generated.

This script is CPU-only and does not launch a GPU or contact the remote node.
The resulting specification is only launchable after the native collector and
the strict profile exporter pass independently.
"""

from __future__ import annotations

import copy
import argparse
import hashlib
import json
from pathlib import Path

import yaml

from faaslora.datasets.workload_generator import FrozenReplayPlan
from scripts import ieee_tc_preflight as p


ROOT = p.ROOT
BASE = ROOT / "paper_results/ieee_tc/p2_backend"
D645_SPEC = BASE / "d645_3b_profiles/source_spec.json"
D699_SPEC = BASE / "d699_3b_output_profile_gaps/source_spec.json"
D698_COVERAGE = BASE / "d698_3b_output_profile_coverage/coverage.json"
CONFIG = ROOT / "configs/ieee_tc/20261017_d641_3b_native_source.yaml"
TRACE = Path(
    "/home/qhq/serverless_llm_baselines/results/paper_experiments/03_main_comparison/"
    "20260509_134259_llama32_3b_main_s8/shared_artifacts/"
    "llama32_3b_r4000_a500_seed42_z1p0_hot48_rot500_s8_mainv1_trace.json"
)
POOL = Path("/home/qhq/serverless_llm_experiment/artifacts/frozen/llama32_3b_a500_v1_modelscope")
OUT = BASE / "d701_3b_same_spec_profile"
OUT_SPEC = OUT / "source_spec.json"
OUTPUT_EDGES = [89, 152, 179, 256]


def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def read(path: Path):
    return json.loads(path.read_text())


def main() -> None:
    if OUT.exists():
        raise FileExistsError(f"append-only output already exists: {OUT}")
    base = read(D645_SPEC)
    gaps = read(D699_SPEC)
    coverage = read(D698_COVERAGE)
    if coverage.get("launchable") is not False or len(coverage.get("missing_classes", [])) != 30:
        raise ValueError("D698 is not the frozen 30-class gap contract")
    if base.get("kind") != "native_source_profile_spec_v1" or gaps.get("kind") != base["kind"]:
        raise ValueError("source-spec kinds differ")
    shared = (
        "trace_sha256", "content_index", "model_overrides", "nvme_budget_bytes",
        "movement_concurrency", "host_parent", "nvme_parent", "workspace_derivation",
        "admission_initialization", "full_development_contract",
    )
    for key in shared:
        if base.get(key) != gaps.get(key):
            raise ValueError(f"D645 and D699 differ in immutable contract field {key}")
    if base["trace_sha256"] != digest(TRACE):
        raise ValueError("trace SHA does not match D645")
    if base["content_index"]["sha256"] != digest(ROOT / base["content_index"]["path"]):
        raise ValueError("content-index SHA does not match D645")
    if base.get("bins", {}).get("declared_output_tokens") != [256]:
        raise ValueError("D645 output-bin contract is not the expected historical contract")
    if gaps.get("bins", {}).get("declared_output_tokens") != OUTPUT_EDGES:
        raise ValueError("D699 output-bin contract changed")
    if len(base.get("representatives", [])) != 24 or len(gaps.get("representatives", [])) != 6:
        raise ValueError("unexpected representative counts")
    base_ids = {row["adapter_id"] for row in base["representatives"]}
    gap_ids = {row["adapter_id"] for row in gaps["representatives"]}
    if not gap_ids <= base_ids:
        raise ValueError("D699 gap identities are not a subset of the D645 identities")
    base_waves = copy.deepcopy(base["waves"])
    gap_waves = [copy.deepcopy(wave) for wave in gaps["waves"] if wave["role"] == "representative_measurement"]
    if len(base_waves) != 46 or len(gap_waves) != 30:
        raise ValueError("unexpected D645/D699 wave counts")
    for index, wave in enumerate(gap_waves, start=len(base_waves)):
        # Keep the D699 target/reference choices but assign new wave identity
        # within one source specification; request IDs are generated by the
        # collector from this ordered list.
        wave["round"] = 3
        wave["group"] = index - len(base_waves)
        wave["source_spec_origin"] = "D699_gap_wave_reused_without_measurement"
    merged = copy.deepcopy(base)
    merged["bins"] = copy.deepcopy(base["bins"])
    merged["bins"]["declared_output_tokens"] = OUTPUT_EDGES
    merged["waves"] = base_waves + gap_waves
    merged["representatives"] = copy.deepcopy(base["representatives"])
    merged["purpose"] = "same_spec_full_native_profile_collection_after_D700_class_gap_closure"
    merged["derivation"] = {
        "kind": "d701_same_spec_append_only_v1",
        "base_source_spec": {"path": str(D645_SPEC), "sha256": digest(D645_SPEC)},
        "gap_source_spec": {"path": str(D699_SPEC), "sha256": digest(D699_SPEC)},
        "gap_coverage": {"path": str(D698_COVERAGE), "sha256": digest(D698_COVERAGE)},
        "new_output_edges": OUTPUT_EDGES,
        "base_wave_count": len(base_waves),
        "appended_gap_wave_count": len(gap_waves),
        "representative_count": len(merged["representatives"]),
        "new_requests_planned": sum(len(w["requests"]) for w in gap_waves),
        "no_new_trace_or_adapter": True,
    }

    # Re-run the existing identity-only input resolver on the merged spec.  It
    # validates the exact frozen trace/content pool and runtime limits without
    # launching a model or making an HTTP request.
    cfg = yaml.safe_load(CONFIG.read_text())["model_profiles"]["llama32_3b_main_modelscope"]["model"]
    cfg.update(
        generation_contract="fixed_length_greedy_v1",
        canonical_prompt_renderer="role_lines_v1",
        max_input_len=759,
        max_output_tokens_cap=256,
        ieee_physical_allocation=True,
        timing_contract="ieee_tc_native_v1",
        ieee_worker_observation=True,
        ieee_gpu_references=True,
        ieee_scheduler_observation=True,
        ieee_input_upper_bounds=[759],
    )
    cfg.update(copy.deepcopy(base["model_overrides"]))
    plan = FrozenReplayPlan.load(TRACE, count=1000, profile="W0")
    spec_path = OUT_SPEC
    OUT.mkdir(parents=True, exist_ok=False)
    spec_path.write_text(json.dumps(merged, indent=2, sort_keys=True) + "\n")
    try:
        p.source_profile_inputs(spec_path, plan, cfg, POOL.resolve(strict=True))
    except Exception:
        # The append-only directory is intentionally not left behind after a
        # failed identity-only preparation; callers may correct a static spec
        # without reusing a partial artifact.
        for path in sorted(OUT.rglob("*"), reverse=True):
            if path.is_file():
                path.unlink()
        OUT.rmdir()
        raise
    manifest = {
        "kind": "d701_3b_same_spec_profile_preparation_v1",
        "campaign": "D701",
        "launchable": False,
        "gpu_runs": 0,
        "dynamic_measurement_required": True,
        "profile_export_authorized": False,
        "representatives": len(merged["representatives"]),
        "waves": len(merged["waves"]),
        "representative_measurement_waves": sum(w["role"] == "representative_measurement" for w in merged["waves"]),
        "planned_requests": sum(len(w["requests"]) for w in merged["waves"]),
        "source_spec": {"path": str(spec_path), "sha256": digest(spec_path)},
        "source_plan": {"path": str(TRACE), "sha256": digest(TRACE), "count": 1000, "profile": "W0"},
        "content_index": {"path": str(ROOT / base["content_index"]["path"]), "sha256": digest(ROOT / base["content_index"]["path"])},
        "source_plan_sha256": p.check_plan(),
        "identity_only_resolver_passed": True,
        "no_new_trace_or_adapter": True,
    }
    (OUT / "prepare.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print(json.dumps(manifest, indent=2, sort_keys=True))


def rebind_graph_config(config_path: Path, out: Path, raw: Path, campaign: str,
                        *, private_host: bool = False) -> None:
    """Reuse D701 cases, not times, under explicit graph/CPU-construction changes."""
    if out.exists():
        raise FileExistsError(f"append-only preparation exists: {out}")
    original = read(OUT_SPEC)
    original_preparation = read(OUT / 'prepare.json')
    if original_preparation['source_spec']['sha256'] != digest(OUT_SPEC):
        raise ValueError('original same-spec preparation changed')
    old_config = yaml.safe_load(CONFIG.read_text())
    new_config = yaml.safe_load(config_path.read_text())
    changed = copy.deepcopy(new_config)
    model_key = 'llama32_3b_main_modelscope'
    graph = changed['model_profiles'][model_key]['model'].pop('compilation_config')
    changes = {'compilation_config': dict(source=None, target=graph)}
    if private_host:
        policy = changed['model_profiles'][model_key]['model'].pop('ieee_host_construction')
        if policy != 'private_cpu_core_commit_v1':
            raise ValueError('unknown private HOST construction policy')
        changes['ieee_host_construction'] = dict(source=None, target=policy)
    if changed != old_config:
        raise ValueError('graph rebind also changes non-graph model or input configuration')
    contract_path = ROOT / original['full_development_contract']['path']
    if digest(contract_path) != original['full_development_contract']['sha256']:
        raise ValueError('original full development contract changed')
    contract = read(contract_path)
    spec = copy.deepcopy(original)
    spec.pop('full_development_contract')
    spec['admission_initialization'].update(
        kind=('native_fixed_output_private_host_length_transfer_v1' if private_host
              else 'native_fixed_output_graph_length_transfer_v1'),
        model_config_changes=changes)
    spec['nvme_parent'] = str(raw.resolve())
    spec['purpose'] = 'same_cases_fresh_native_timings_after_explicit_graph_coverage_change'
    spec['derivation'] = dict(kind='same_spec_graph_rebind_v1', campaign=campaign,
        source_spec=dict(path=str(OUT_SPEC), sha256=digest(OUT_SPEC)),
        source_contract=dict(path=str(contract_path), sha256=digest(contract_path)),
        source_config=dict(path=str(CONFIG), sha256=digest(CONFIG)),
        candidate_config=dict(path=str(config_path), sha256=digest(config_path)),
        requests_changed=False, timing_samples_reused=False)
    if private_host:
        spec['purpose'] = 'same_cases_fresh_native_timings_after_private_cpu_construction_change'
        spec['derivation']['kind'] = 'same_spec_private_host_rebind_v1'
        previous = BASE / 'd725_3b_graph_profile/source_spec.json'
        previous_spec = read(previous)
        if (previous_spec['waves'] != spec['waves']
                or previous_spec['representatives'] != spec['representatives']):
            raise ValueError('private HOST collection differs from completed D725 cases')
        spec['derivation']['previous_measured_spec'] = dict(path=str(previous), sha256=digest(previous))
    cfg = copy.deepcopy(new_config['model_profiles'][model_key]['model'])
    cfg.update(generation_contract='fixed_length_greedy_v1',
        canonical_prompt_renderer='role_lines_v1', max_input_len=759,
        max_output_tokens_cap=256, ieee_physical_allocation=True,
        timing_contract='ieee_tc_native_v1', ieee_worker_observation=True,
        ieee_gpu_references=True, ieee_scheduler_observation=True,
        ieee_input_upper_bounds=[759])
    cfg.update(copy.deepcopy(spec['model_overrides']))
    runtime = ROOT / 'results/ieee_tc/p2_backend_qualification/runtime_20260926/cuda_import_attempt3.json'
    kwargs = dict(backend_version=read(runtime)['modules']['vllm']['version'],
        runtime_receipt_sha256=digest(runtime), source_trace_sha256=spec['trace_sha256'])
    _, evidence, assembly = p.prepare_admission_source_runtime(cfg, spec, **kwargs)
    if (assembly['planned_child_model_config']['ieee_admission_profile']['profile_means']
            != contract['model_config']['ieee_admission_profile']['profile_means']):
        raise ValueError('graph-only rebind changed the completed fixed-output means')
    contract.update(model_config=assembly['planned_child_model_config'],
        base_config_sha256=digest(config_path), completed_length_binding=spec['admission_initialization'],
        derivation=copy.deepcopy(spec['derivation']), plan_sha256=p.check_plan())
    out.mkdir(parents=True, exist_ok=False)
    def save(name, value):
        path = out / name
        with path.open('x') as stream:
            json.dump(value, stream, indent=2, sort_keys=True, allow_nan=False)
            stream.write('\n')
        return dict(path=str(path), sha256=digest(path))
    spec['full_development_contract'] = save('development_contract.json', contract)
    source_ref = save('source_spec.json', spec)
    _, _, checked = p.prepare_admission_source_runtime(cfg, spec, **kwargs)
    plan = FrozenReplayPlan.load(TRACE, count=1000, profile='W0')
    _, _, identities, waves, _ = p.source_profile_inputs(out/'source_spec.json', plan, cfg, POOL.resolve(strict=True))
    assert spec['waves'] == original['waves'] and spec['representatives'] == original['representatives']
    assert len(identities) == 24 and len(waves) == 76 and sum(map(len, waves)) == 423
    manifest = dict(kind='d701_3b_same_spec_profile_preparation_v1', campaign=campaign,
        preparation_schema_reused=True, launchable=False, gpu_runs=0,
        dynamic_measurement_required=True, profile_export_authorized=False,
        representatives=24, waves=76, planned_requests=423,
        representative_measurement_waves=sum(w['role']=='representative_measurement' for w in spec['waves']),
        source_spec=source_ref, source_plan=original_preparation['source_plan'],
        content_index=original_preparation['content_index'], source_plan_sha256=p.check_plan(),
        identity_only_resolver_passed=True, no_new_trace_or_adapter=True,
        length_initialization=evidence, assembly=checked, timing_samples_reused=False)
    save('prepare.json', manifest)
    print(json.dumps(dict(passed=True, campaign=campaign, requests=423, waves=76,
        model_backend_id=contract['model_config']['ieee_admission_profile']['model_backend_id'],
        timing_samples_reused=False)))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rebind-graph-config', type=Path)
    parser.add_argument('--rebind-private-host-config', type=Path)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--raw-directory', type=Path)
    parser.add_argument('--campaign')
    args = parser.parse_args()
    selected_config = args.rebind_graph_config or args.rebind_private_host_config
    if args.rebind_graph_config and args.rebind_private_host_config:
        parser.error('choose one configuration rebind')
    if selected_config:
        if not all((args.output, args.raw_directory, args.campaign)):
            parser.error('graph rebind requires output, raw-directory and campaign')
        rebind_graph_config(selected_config.resolve(strict=True), args.output.resolve(),
                            args.raw_directory.resolve(), args.campaign,
                            private_host=bool(args.rebind_private_host_config))
    else:
        if any((args.output, args.raw_directory, args.campaign)):
            parser.error('output overrides require rebind-graph-config')
        main()
